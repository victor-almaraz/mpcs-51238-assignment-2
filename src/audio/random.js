// Seeded PRNG used by all audio code; audio code never calls Math.random() (audio-engine-core.md).

export function mulberry32(seed) {
  let a = seed | 0;
  return function () {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Combines integers into one 32-bit seed (FNV-1a over the values). */
export function hashSeed(...parts) {
  let h = 0x811c9dc5;
  for (const p of parts) {
    h ^= p | 0;
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0 || 1;
}
